export function createDefaultGlyphLibrary(): Record<string, GlyphData> {
  const map: Record<string, GlyphData> = {};
  for (const raw of RAW_PERSIAN_MASTERS) {
    const g = buildGlyphFromRaw(raw, 9, 11);
    map[g.id] = g;
  }
  for (const lat of createLatinMasters()) {
    map[lat.id] = lat;
  }
  return map;
}

export function getOrderedGlyphIds(library: Record<string, GlyphData>): string[] {
  return Object.keys(library);
}
